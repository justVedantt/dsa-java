package operators;

public class assignmentOp {
    public static void main(String[] args) {
        int a = 1;
        a += 1;
        System.out.println(a);
        int b = 5;
        b -= 5;
        System.out.println(b);
        int c = 10;
        c *= 10;
        System.out.println(c);
        int d = 20;
        d /= 20;
        System.out.println(d);
    }
}
