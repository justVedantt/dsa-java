package operators;

public class relationalOp {
    public static void main(String[] args) {
        int a = 10;
        int b = 39;
        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);
    }
}
